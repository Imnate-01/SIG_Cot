const check = (name, cond, extra='') => { if (cond) { ok++; console.log('  ✓', name); } else { fail++; console.log('  ✗', name, extra); } };
const expectError = async (name, fn) => { try { await fn(); check(name, false, '(no lanzó error)'); } catch (e) { check(name, true); return e; } };

