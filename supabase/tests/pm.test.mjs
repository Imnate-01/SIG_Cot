// Prueba de la migración 20261023_01 (módulo PM) contra PGlite.
// Ejecutar: cd supabase/tests && npm install && npm test

import { PGlite } from '@electric-sql/pglite';
import { readFileSync } from 'node:fs';
const db = new PGlite();
const q = (s, p) => db.query(s, p);
let ok = 0, fail = 0;
const check = (name, cond, extra = '') => { if (cond) { ok++; console.log('  ✓', name); } else { fail++; console.log('  ✗', name, extra); } };
const expectError = async (name, fn) => { try { await fn(); check(name, false, '(no lanzó error)'); } catch (e) { check(name, true); } };
const sql = readFileSync(new URL('../migrations/20261023_01_modulo_pm.sql', import.meta.url), 'utf8');
const fmt = (d) => new Date(d).toISOString().slice(0, 10);

await db.exec(`create role anon; create role authenticated;
  create table clientes (id bigint generated by default as identity primary key, nombre text not null);
  insert into clientes (nombre) values ('Nestlé');`);
await db.exec(sql);
await db.exec(sql);
console.log('Migración aplicada y re-aplicada (idempotente) ✓');

console.log('plantilla');
const pl = (await q(`select count(*)::int n, count(distinct codigo)::int c from pm_plantilla_tareas`)).rows[0];
check('31 tareas únicas', pl.n === 31 && pl.c === 31, JSON.stringify(pl));
const ev = (await q(`select evidencia, count(*)::int n from pm_plantilla_tareas group by 1 order by 1`)).rows;
check('12 obligatorias, 15 opcionales, 4 sin evidencia', JSON.stringify(ev) === JSON.stringify([{ evidencia: 'none', n: 4 }, { evidencia: 'optional', n: 15 }, { evidencia: 'required', n: 12 }]), JSON.stringify(ev));
const etapas = (await q(`select etapa_orden, semanas, count(*)::int n from pm_plantilla_tareas group by 1,2 order by 1`)).rows.map(r => `${r.semanas}:${r.n}`).join(' ');
check('etapas (semanas:tareas) como en el Excel', etapas === '-18:4 -17:3 -16:2 -4:1 -2:6 0:5 1:6 3:4', etapas);

console.log('pm_crear_expediente');
const dat = { cliente_id: 1, fecha_inicio: '2027-08-08', planta: ' Planta 1 ', linea: 'Línea 3', sam: '', creado_por: '11111111-1111-1111-1111-111111111111' };
const exp = (await q(`select * from pm_crear_expediente($1::jsonb)`, [JSON.stringify(dat)])).rows[0];
check('crea el PM (activo, texto limpio, vacío → null)', exp.estado === 'active' && exp.planta === 'Planta 1' && exp.sam === null);
const tareas = (await q(`select codigo, fecha_limite, semanas from pm_tareas where expediente_id=$1 order by orden`, [exp.id])).rows;
check('genera las 31 tareas', tareas.length === 31);
const esperadas = { 'PM-01': '2027-04-04', 'PM-05': '2027-04-11', 'PM-08': '2027-04-18', 'PM-10': '2027-07-11', 'PM-11': '2027-07-25', 'PM-20': '2027-08-08', 'PM-27': '2027-08-15', 'PM-33': '2027-08-29' };
check('fechas límite = inicio + semanas×7 (126, 119, 112, 28, 14, 0, 7, 21 días)',
  Object.entries(esperadas).every(([c, f]) => fmt(tareas.find(t => t.codigo === c).fecha_limite) === f),
  JSON.stringify(tareas.filter(t => esperadas[t.codigo]).map(t => [t.codigo, fmt(t.fecha_limite)])));
await expectError('sin cliente → error', () => q(`select pm_crear_expediente('{"fecha_inicio":"2027-08-08"}'::jsonb)`));
await expectError('cliente inexistente → error y no deja PM huérfano', () => q(`select pm_crear_expediente('{"cliente_id":99,"fecha_inicio":"2027-08-08"}'::jsonb)`));
check('…sin PM huérfano', (await q(`select count(*)::int n from pm_expedientes`)).rows[0].n === 1);

console.log('pm_cambiar_fecha_inicio');
await q(`update pm_tareas set completada=true, completada_por='11111111-1111-1111-1111-111111111111', completada_en=now() where expediente_id=$1 and codigo='PM-01'`, [exp.id]);
await q(`select pm_cambiar_fecha_inicio($1::uuid, '2027-09-01'::date, null)`, [exp.id]);
const t2 = (await q(`select codigo, fecha_limite, completada from pm_tareas where expediente_id=$1`, [exp.id])).rows;
check('tarea completada conserva su fecha (04/04)', fmt(t2.find(t => t.codigo === 'PM-01').fecha_limite) === '2027-04-04');
check('tarea pendiente se recalcula: 01/09 − 126 días = 28/04 (PM-02)', fmt(t2.find(t => t.codigo === 'PM-02').fecha_limite) === '2027-04-28', fmt(t2.find(t => t.codigo === 'PM-02').fecha_limite));
check('ejecución: 01/09', fmt(t2.find(t => t.codigo === 'PM-20').fecha_limite) === '2027-09-01');
check('historial registra 30 cambios (las pendientes)', (await q(`select count(*)::int n from pm_tarea_historial where accion='due_date_changed'`)).rows[0].n === 30);
await expectError('PM inexistente → error', () => q(`select pm_cambiar_fecha_inicio('00000000-0000-0000-0000-000000000000'::uuid, '2027-09-01'::date, null)`));

console.log('reglas de datos');
await expectError('tarea no completada no puede tener completada_por', () => q(`update pm_tareas set completada_por='11111111-1111-1111-1111-111111111111' where expediente_id=$1 and codigo='PM-02'`, [exp.id]));
await expectError('fecha_fin anterior a inicio → error', () => q(`update pm_expedientes set fecha_fin='2027-01-01' where id=$1`, [exp.id]));
await q(`insert into pm_tarea_colaboradores (tarea_id, usuario_id) select id, '22222222-2222-2222-2222-222222222222' from pm_tareas where codigo='PM-01' limit 1`);
await expectError('colaborador repetido → error', () => q(`insert into pm_tarea_colaboradores (tarea_id, usuario_id) select id, '22222222-2222-2222-2222-222222222222' from pm_tareas where codigo='PM-01' limit 1`));
await q(`delete from pm_expedientes where id=$1`, [exp.id]);
check('borrar el PM borra tareas, colaboradores e historial', (await q(`select (select count(*) from pm_tareas)::int + (select count(*) from pm_tarea_colaboradores)::int + (select count(*) from pm_tarea_historial)::int n`)).rows[0].n === 0);

console.log('permisos');
const perms = (await q(`select p.proname, has_function_privilege('anon', p.oid, 'execute') anon, has_function_privilege('authenticated', p.oid, 'execute') auth from pg_proc p where p.proname like 'pm\\_%'`)).rows;
check('anon NO ejecuta, authenticated sí', perms.length === 2 && perms.every(p => !p.anon && p.auth), JSON.stringify(perms));
const rls = (await q(`select relname, relrowsecurity from pg_class where relname like 'pm\\_%' and relkind='r'`)).rows;
check('RLS activa en las 5 tablas', rls.length === 5 && rls.every(r => r.relrowsecurity), JSON.stringify(rls));
const anonSel = (await q(`select count(*)::int n from information_schema.role_table_grants where grantee='anon' and table_name like 'pm\\_%'`)).rows[0].n;
check('anon sin permisos sobre tablas pm_*', anonSel === 0, String(anonSel));

console.log(`\n${ok} pasaron, ${fail} fallaron`);
process.exit(fail ? 1 : 0);
