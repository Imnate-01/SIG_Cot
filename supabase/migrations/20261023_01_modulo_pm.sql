-- =============================================================================
-- Módulo PM (Preventive Maintenance) — checklist de actividades por cliente
-- =============================================================================
-- Reemplaza el Excel "SIG PM Execution Tracker". Un EXPEDIENTE es un PM de un
-- cliente (planta / línea); al crearlo se generan sus 31 tareas con fecha
-- límite = fecha de inicio del PM + (semanas × 7 días).
--
-- Tablas:
--   pm_plantilla_tareas      las 31 tareas fijas (editables a futuro sin código)
--   pm_expedientes           un PM por cliente
--   pm_tareas                tareas de cada PM (copia de la plantilla + estado)
--   pm_tarea_colaboradores   quién colabora en una tarea (además de quien la completa)
--   pm_tarea_historial       bitácora de cambios por tarea
--
-- Funciones (una transacción cada una, SECURITY INVOKER → respetan RLS):
--   pm_crear_expediente(jsonb)               crea el PM y sus tareas
--   pm_cambiar_fecha_inicio(uuid, date)      recalcula fechas SOLO de tareas pendientes
--
-- Evidencias (archivos/fotos): fase 2 (tabla pm_evidencias + Storage). La
-- plantilla ya indica qué tareas la piden (columna `evidencia`).
--
-- Idempotente: se puede ejecutar más de una vez.
-- Cómo aplicarla: Supabase → SQL Editor → pegar y ejecutar.
-- =============================================================================

-- ─── 1. Plantilla de tareas ─────────────────────────────────────────────────
create table if not exists public.pm_plantilla_tareas (
  id           bigint generated by default as identity primary key,
  codigo       text    not null unique,                       -- 'PM-01'
  etapa_orden  integer not null,                              -- 1..8
  etapa        text    not null,                              -- '18 weeks before PM'
  semanas      integer not null,                              -- negativo = antes del PM
  titulo       text    not null,
  evidencia    text    not null default 'none'
               check (evidencia in ('none', 'optional', 'required')),
  orden        integer not null,
  activa       boolean not null default true
);

-- ─── 2. Expedientes (un PM de un cliente) ───────────────────────────────────
create table if not exists public.pm_expedientes (
  id               uuid primary key default gen_random_uuid(),
  cliente_id       bigint not null references public.clientes(id),
  planta           text,
  linea            text,                                      -- Machine / Line
  contacto_nombre  text,
  contacto_telefono text,
  contacto_correo  text,
  sam              text,
  po_numero        text,
  fse_filler       text,
  fse_downline     text,
  fecha_inicio     date not null,
  fecha_fin        date,
  estado           text not null default 'active'
                   check (estado in ('active', 'completed', 'cancelled')),
  notas_abiertas   text,
  creado_por       uuid,
  created_at       timestamptz not null default now(),
  updated_at       timestamptz not null default now(),
  check (fecha_fin is null or fecha_fin >= fecha_inicio)
);
create index if not exists pm_expedientes_cliente_idx on public.pm_expedientes(cliente_id);
create index if not exists pm_expedientes_estado_idx  on public.pm_expedientes(estado, fecha_inicio);

-- ─── 3. Tareas de cada PM ───────────────────────────────────────────────────
-- Se copian título/etapa/evidencia de la plantilla: si la plantilla cambia
-- después, los PM ya creados no se alteran.
create table if not exists public.pm_tareas (
  id             uuid primary key default gen_random_uuid(),
  expediente_id  uuid not null references public.pm_expedientes(id) on delete cascade,
  plantilla_id   bigint references public.pm_plantilla_tareas(id) on delete set null,
  codigo         text    not null,
  etapa_orden    integer not null,
  etapa          text    not null,
  semanas        integer not null,
  titulo         text    not null,
  evidencia      text    not null default 'none'
                 check (evidencia in ('none', 'optional', 'required')),
  orden          integer not null,
  fecha_limite   date,
  asignado_a     uuid,                                        -- responsable (opcional) antes de completarla
  completada     boolean not null default false,
  completada_por uuid,
  completada_en  timestamptz,
  notas          text,
  updated_by     uuid,
  updated_at     timestamptz not null default now(),
  unique (expediente_id, codigo),
  check (completada or (completada_por is null and completada_en is null))
);
create index if not exists pm_tareas_expediente_idx on public.pm_tareas(expediente_id, orden);
create index if not exists pm_tareas_pendientes_idx on public.pm_tareas(fecha_limite) where not completada;

-- ─── 4. Colaboradores por tarea ─────────────────────────────────────────────
create table if not exists public.pm_tarea_colaboradores (
  tarea_id   uuid not null references public.pm_tareas(id) on delete cascade,
  usuario_id uuid not null,
  agregado_por uuid,
  created_at timestamptz not null default now(),
  primary key (tarea_id, usuario_id)
);

-- ─── 5. Historial ───────────────────────────────────────────────────────────
create table if not exists public.pm_tarea_historial (
  id         bigint generated by default as identity primary key,
  tarea_id   uuid not null references public.pm_tareas(id) on delete cascade,
  usuario_id uuid,
  accion     text not null,   -- completed | reopened | note | assigned | collaborator_added | collaborator_removed | due_date_changed
  detalle    jsonb,
  created_at timestamptz not null default now()
);
create index if not exists pm_tarea_historial_tarea_idx on public.pm_tarea_historial(tarea_id, created_at desc);

-- ─── 6. RLS: solo usuarios con sesión (igual que el resto de la app) ────────
do $$
declare
  t text;
  tablas text[] := array[
    'pm_plantilla_tareas', 'pm_expedientes', 'pm_tareas',
    'pm_tarea_colaboradores', 'pm_tarea_historial'
  ];
begin
  foreach t in array tablas loop
    execute format('alter table public.%I enable row level security', t);
    execute format('drop policy if exists %I on public.%I', t || '_autenticados', t);
    execute format(
      'create policy %I on public.%I for all to authenticated using (true) with check (true)',
      t || '_autenticados', t
    );
    execute format('revoke all on public.%I from anon', t);
  end loop;
end $$;

