-- ─── 8. Crear un PM con sus tareas (atómico) ────────────────────────────────
-- p_datos: { cliente_id, fecha_inicio, fecha_fin?, planta?, linea?, contacto_nombre?,
--            contacto_telefono?, contacto_correo?, sam?, po_numero?, fse_filler?,
--            fse_downline?, creado_por? }
create or replace function public.pm_crear_expediente(p_datos jsonb)
returns public.pm_expedientes
language plpgsql
security invoker
set search_path = public
as $$
declare
  v_exp public.pm_expedientes;
begin
  if p_datos is null or p_datos->>'cliente_id' is null or p_datos->>'fecha_inicio' is null then
    raise exception 'cliente_id y fecha_inicio son obligatorios' using errcode = '22023';
  end if;

  insert into public.pm_expedientes
    (cliente_id, planta, linea, contacto_nombre, contacto_telefono, contacto_correo,
     sam, po_numero, fse_filler, fse_downline, fecha_inicio, fecha_fin, creado_por)
  values
    ((p_datos->>'cliente_id')::bigint,
     nullif(btrim(p_datos->>'planta'), ''),
     nullif(btrim(p_datos->>'linea'), ''),
     nullif(btrim(p_datos->>'contacto_nombre'), ''),
     nullif(btrim(p_datos->>'contacto_telefono'), ''),
     nullif(btrim(p_datos->>'contacto_correo'), ''),
     nullif(btrim(p_datos->>'sam'), ''),
     nullif(btrim(p_datos->>'po_numero'), ''),
     nullif(btrim(p_datos->>'fse_filler'), ''),
     nullif(btrim(p_datos->>'fse_downline'), ''),
     (p_datos->>'fecha_inicio')::date,
     nullif(p_datos->>'fecha_fin', '')::date,
     nullif(p_datos->>'creado_por', '')::uuid)
  returning * into v_exp;

  insert into public.pm_tareas
    (expediente_id, plantilla_id, codigo, etapa_orden, etapa, semanas, titulo, evidencia, orden, fecha_limite)
  select v_exp.id, p.id, p.codigo, p.etapa_orden, p.etapa, p.semanas, p.titulo, p.evidencia, p.orden,
         v_exp.fecha_inicio + (p.semanas * 7)
  from public.pm_plantilla_tareas p
  where p.activa
  order by p.orden;

  return v_exp;
end;
$$;

-- ─── 9. Cambiar la fecha de inicio: recalcula solo las tareas PENDIENTES ────
create or replace function public.pm_cambiar_fecha_inicio(p_expediente uuid, p_fecha date, p_usuario uuid default null)
returns public.pm_expedientes
language plpgsql
security invoker
set search_path = public
as $$
declare
  v_exp public.pm_expedientes;
begin
  if p_fecha is null then
    raise exception 'La fecha de inicio es obligatoria' using errcode = '22023';
  end if;

  update public.pm_expedientes
     set fecha_inicio = p_fecha, updated_at = now()
   where id = p_expediente
  returning * into v_exp;

  if not found then
    raise exception 'PM no encontrado' using errcode = 'P0002';
  end if;

  -- Bitácora: solo de las tareas cuya fecha realmente cambia
  insert into public.pm_tarea_historial (tarea_id, usuario_id, accion, detalle)
  select t.id, p_usuario, 'due_date_changed',
         jsonb_build_object('from', t.fecha_limite, 'to', p_fecha + (t.semanas * 7))
    from public.pm_tareas t
   where t.expediente_id = p_expediente and not t.completada
     and t.fecha_limite is distinct from p_fecha + (t.semanas * 7);

  update public.pm_tareas
     set fecha_limite = p_fecha + (semanas * 7), updated_at = now()
   where expediente_id = p_expediente and not completada;

  return v_exp;
end;
$$;

revoke all on function public.pm_crear_expediente(jsonb) from public, anon;
revoke all on function public.pm_cambiar_fecha_inicio(uuid, date, uuid) from public, anon;
grant execute on function public.pm_crear_expediente(jsonb) to authenticated;
grant execute on function public.pm_cambiar_fecha_inicio(uuid, date, uuid) to authenticated;

notify pgrst, 'reload schema';
